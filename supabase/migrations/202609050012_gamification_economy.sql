set avatar = u.raw_user_meta_data ->> 'avatar'
from auth.users u
where u.id = p.id
  and p.avatar is null
  and u.raw_user_meta_data ->> 'avatar' in (
    select seed
    from public.avatar_catalog
    where is_starter
      and is_active
  );

-- Existing balances are initialized only once, so re-running this migration
-- cannot restore coins already spent by a user.
update public.profiles
set
  coin_balance = floor(greatest(coalesce(total_xp, 0), 0)::numeric / 10)::integer,
  total_coins_earned = floor(greatest(coalesce(total_xp, 0), 0)::numeric / 10)::integer,
  economy_initialized_at = now()
where economy_initialized_at is null;

