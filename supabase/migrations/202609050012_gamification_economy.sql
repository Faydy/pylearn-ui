-- PyLearn economy: XP remains permanent, while coins are earned from the same
-- trusted profile XP update that follows a first accepted problem submission.

alter table public.profiles
  add column if not exists coin_balance integer not null default 0;

alter table public.profiles
  add column if not exists total_coins_earned integer not null default 0;

alter table public.profiles
  add column if not exists economy_initialized_at timestamptz;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'profiles_coin_balance_nonnegative'
      and conrelid = 'public.profiles'::regclass
  ) then
    alter table public.profiles
      add constraint profiles_coin_balance_nonnegative check (coin_balance >= 0);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'profiles_total_coins_earned_nonnegative'
      and conrelid = 'public.profiles'::regclass
  ) then
    alter table public.profiles
      add constraint profiles_total_coins_earned_nonnegative check (total_coins_earned >= 0);
  end if;
end;
$$;

-- Avatar URLs are deliberately not stored. The seed is rendered centrally by
-- the existing DiceBear utility in the frontend.
create table if not exists public.avatar_catalog (
  id bigint generated by default as identity primary key,
  name text not null,
  seed varchar(64) not null unique,
  gender_style text not null default 'neutral',
  price_coins integer not null default 0,
  required_level integer not null default 0,
  rarity text not null default 'common',
  is_active boolean not null default true,
  is_starter boolean not null default false,
  is_free boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint avatar_catalog_name_not_blank check (length(btrim(name)) > 0),
  constraint avatar_catalog_price_nonnegative check (price_coins >= 0),
  constraint avatar_catalog_level_nonnegative check (required_level >= 0),
  constraint avatar_catalog_gender_style_check check (gender_style in ('feminine', 'masculine', 'neutral')),
  constraint avatar_catalog_rarity_check check (rarity in ('common', 'rare', 'epic', 'legendary')),
  constraint avatar_catalog_free_price_check check (not is_free or price_coins = 0)
);

create table if not exists public.user_avatars (
  user_id uuid not null references public.profiles(id) on delete cascade,
  avatar_id bigint not null references public.avatar_catalog(id) on delete restrict,
  purchased_at timestamptz not null default now(),
  primary key (user_id, avatar_id)
);

create index if not exists user_avatars_avatar_id_idx
  on public.user_avatars (avatar_id);

create table if not exists public.coin_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount integer not null,
  transaction_type text not null,
  reason text not null,
  reference_id bigint,
  created_at timestamptz not null default now(),
  constraint coin_transactions_amount_nonzero check (amount <> 0),
  constraint coin_transactions_type_check check (transaction_type in ('earned', 'spent'))
);

create index if not exists coin_transactions_user_created_at_idx
  on public.coin_transactions (user_id, created_at desc);

